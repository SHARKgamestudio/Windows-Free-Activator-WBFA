int shell_run_command(const char* command, bool as_admin, bool show_console) {
    if (!command)
        return ERROR_INVALID_PARAMETER;

    SHELLEXECUTEINFOA sei = { 0 };

    sei.cbSize = sizeof(sei);
    sei.fMask = SEE_MASK_ASYNCOK;
    sei.lpVerb = as_admin ? "runas" : "";
    sei.lpFile = "cmd.exe";

    char params[4096];
    snprintf(params, sizeof(params), "/c \"%s\"", command);

    sei.lpParameters = params;
    sei.nShow = show_console ? SW_SHOW : SW_HIDE;

    HINSTANCE test0 = sei.hInstApp;

    if (!ShellExecuteExA(&sei))
        return (int)GetLastError();

    HINSTANCE test1 = sei.hInstApp;

    WaitForSingleObject(sei.hProcess, INFINITE);

    HINSTANCE test2 = sei.hInstApp;

    DWORD exitCode = 0;
    GetExitCodeProcess(sei.hProcess, &exitCode);

    CloseHandle(sei.hProcess);

    return (int)exitCode;
}

